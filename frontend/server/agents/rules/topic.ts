/* ------------------------------------------------------------------
 * 话题规则引擎 —— 情绪主诉识别 + 话题切换检测（确定性，不经 LLM）
 *
 * 为什么需要这一层：
 *   分诊会话把槽位（部位/时长/性质）和轮次存在前端 ref 里，每轮带回服务端。
 *   服务端原来只看 `round > 0` 就判定"用户在回答追问"，直接沿用旧槽位。
 *   后果是用户换了一个全新话题（比如从"肚子疼"跳到"我失恋了"）时，
 *   旧症状槽位被硬套到新主诉上，模型把两件事揉成一句 ——
 *   "肚子胀痛三天 + 阿司匹林 + 失恋" 这种四不像就是这么来的。
 *
 *   同样不能靠模型判断"是不是新话题"：这发生在 Supervisor 之前，
 *   此时还没决定要不要调模型，而且这是个确定性的状态机判断，
 *   规则表又快又稳，答辩也能现场演示。
 * ------------------------------------------------------------------ */

/** 情绪/心理困扰主诉的关键词。命中即走心理科路径，不再问"哪个部位、多久"。 */
const EMOTION_PATTERN =
  /(失恋|分手|离婚|被甩|暗恋|单相思|喜欢的人|心碎|难过|难受想哭|想哭|哭了|心情不好|心情低落|情绪低落|心里堵|心里难受|心里不舒服|抑郁|焦虑|压力(大|很大|好大|太大)|撑不住|受不了|崩溃|烦躁|靠谱吗.*(恋爱|感情)|感情(问题|困扰)|男朋友|女朋友|对象.*(分手|吵架))/;

export interface EmotionSignal {
  hit: boolean;
  /** 命中的关键词，供 reason 与前端展示，不记录整句原文 */
  matched: string | null;
}

/**
 * 识别情绪主诉。返回命中与否 + 命中的词。
 *
 * <p>判据保守：只认明确指向心理/情绪的词，不含泛化的"不舒服"
 * （那个词在躯体症状里太常见，误判会把真正的身体不适带偏）。
 */
export function detectEmotion(text: string): EmotionSignal {
  const m = text.match(EMOTION_PATTERN);
  return m ? { hit: true, matched: m[0] } : { hit: false, matched: null };
}

/**
 * 判断本轮是否是一个"新话题"，需要丢弃旧槽位、重新走调度。
 *
 * <p>调用前提：`round > 0`（即上一轮停在追问态）。判据按优先级：
 * <ol>
 *   <li>情绪主诉 → 一定是新话题（用户从身体症状切到情绪问题）</li>
 *   <li>出现明确的"新症状"词且旧槽位里没有相关部位 → 新话题</li>
 *   <li>其余（短回答、部位/时长补充）→ 延续追问</li>
 * </ol>
 *
 * <p><b>保守原则</b>：拿不准时判为"延续"（返回 false）。误判成新话题会
 * 丢掉患者刚说的症状，比多问一句更糟。所以第二条要求"新症状词 + 旧槽位
 * 无对应"同时成立才切换。
 *
 * @param text       本轮用户原话（已脱敏、不含健康档案前缀）
 * @param knownSlots 上一轮累积的槽位
 */
export function isTopicSwitch(
  text: string,
  knownSlots: Record<string, string | undefined>,
): boolean {
  if (detectEmotion(text).hit) return true;

  /*
   * 新症状词：这些都是"全新主诉"的强信号，正常回答追问时不会凭空出现。
   * 例如旧槽位是「肚子/三天/胀痛」，用户突然说"我头晕得厉害" —— 头晕
   * 不在旧槽位里，是新问题，应重新分诊。
   *
   * 用"词不在旧槽位的字符串值里"做粗判，避免把"昨天头还是疼"这种
   * 补充描述误当新话题（那种情况"疼/头"往往已在槽位里）。
   */
  const NEW_COMPLAINT =
    /(头晕|头疼|头痛|胸闷|心慌|心悸|发烧|发热|咳嗽|咳痰|呕吐|腹泻|皮疹|尿频|尿痛|关节疼|腰疼|膝盖疼)/;
  const m = text.match(NEW_COMPLAINT);
  if (!m) return false;

  const knownBlob = Object.values(knownSlots).filter(Boolean).join(' ');
  return !knownBlob.includes(m[0].slice(0, 2));
}

