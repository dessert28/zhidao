/* ------------------------------------------------------------------
 * 健康档案按需注入的判断（纯函数）
 *
 * 为什么需要：健康档案原来每轮都拼进问题里。用户聊情绪、打招呼、
 * 说"重来"之后的闲聊时也带着"高血压/阿司匹林"，模型容易把这些
 * 背景当成用户此刻在描述的症状，答非所问（实测"失恋"被答成
 * "肚子胀痛 + 在吃阿司匹林"）。
 *
 * 这里判断"这一轮需不需要带档案"：
 *   · 情绪主诉 / 打招呼 / 感谢 → 不带（这些轮次与档案无关）
 *   · 其余（症状、用药、指标、年龄相关）→ 带
 *
 * 判据保守：拿不准时**带档案**（返回 true）—— 少带一次不会出错，
 * 但漏带一次会让本该个性化的回答变成泛泛而谈。
 * ------------------------------------------------------------------ */

/** 与服务端 rules/topic.ts 的 EMOTION_PATTERN 保持一致 */
const EMOTION =
  /(失恋|分手|离婚|被甩|暗恋|单相思|喜欢的人|心碎|难过|想哭|哭了|心情不好|心情低落|情绪低落|心里堵|心里难受|心里不舒服|抑郁|焦虑|压力(大|很大|好大|太大)|撑不住|受不了|崩溃|烦躁|感情(问题|困扰)|男朋友|女朋友)/;

/*
 * 纯社交轮次：打招呼、感谢、重来等，不涉及健康问题。
 *
 * 刻意**不含**单独的"嗯/好/三天了" —— 那些是分诊追问的常见回答，
 * 判成社交会漏带档案。宁可保守带上（多一段上下文无害），
 * 也不能在追问中途突然把档案撤掉。
 */
const SOCIAL =
  /^(你好|您好|嗨|hi|hello|在吗|谢谢|感谢您?|收到|明白了?|知道了?|OK|ok|再见|拜拜|重来|重新开始)[。，！!~ ～\s]*$/i;

/**
 * 这一轮是否需要附带健康档案摘要。
 *
 * @param question 用户本轮输入（原始文本，脱敏前后都行 —— 这里只看关键词）
 */
export function needsHealthContext(question: string): boolean {
  const t = question.trim();
  if (!t) return false;
  if (EMOTION.test(t)) return false;
  if (SOCIAL.test(t)) return false;
  return true;
}
