def add_point_table(doc, rows, widths=None, size=8.1):
    """创新点对照表：无表头。

    这三行本身自带「常见做法 / 本项目做法 / 技术价值」标签，再加一行
    「内容」表头等于重复一次信息，还多占一行版面。
    """
    tbl = add_table(doc, ["", ""], rows, widths=widths or [2.6, 12.8], size=size)
    tbl._tbl.remove(tbl.rows[0]._tr)
    return tbl

